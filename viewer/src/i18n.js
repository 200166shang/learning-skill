export function preferredLanguage(systemLanguage = "", storedLanguage = null) {
  if (storedLanguage === "zh" || storedLanguage === "en") return storedLanguage;
  return String(systemLanguage).toLowerCase().startsWith("zh") ? "zh" : "en";
}

export const otherLanguage = (language) => language === "zh" ? "en" : "zh";
export const copyFor = (language) => translations[language] || translations.en;
